class Contenido(Temporal):
    def test_lo_generado_trae_los_valores_exactos_y_nombres_validos_de_csharp(self):
        for datos in (MONEDA, TIPO_ARREGLO, ESTADO_VERSION, SIN_RESPUESTA):
            self.poner(datos)
        texto = self.generar()
        self.assertIn("public enum EstadoDeVersionDePlantilla", texto)
        self.assertIn("Vigente = 159460002,", texto)
        self.assertIn("ElClienteNoVolvioAEscribir = 159460003,", texto)
        miembros = re.findall(r"^\s+(\w+) = (\d+),$", texto, re.M)
        self.assertIn(("Cordobas", "159460001"), miembros)
        self.assertIn(("Dolares", "159460002"), miembros)
        self.assertEqual(len(miembros), 2 + 2 + 3 + 2)
        for nombre in re.findall(r"^\s+(\w+) = \d+,$", texto, re.M):
            self.assertRegex(nombre, r"^[A-Za-z_][A-Za-z0-9_]*$")
        self.assertEqual(len(re.findall(r"public enum ", texto)), 4)

    def test_el_formato_exacto_de_un_choice(self):
        self.poner(MONEDA)
        esperado = (
            "// <auto-generated>\n"
            "// Generado por herramientas/codigo/generar_enums.py desde playbooks-de-prueba/choice-global/.\n"
            "// NO editar a mano: cambia el playbook del choice y se vuelve a generar.\n"
            "// </auto-generated>\n"
            "namespace Prueba.Plugins.Dominio\n{\n"
            "    /// <summary>Choice global <c>sanic_carp_ch_moneda</c> (CH - CARP - Moneda).</summary>\n"
            "    public enum Moneda\n    {\n"
            "        /// <summary>Cordobas</summary>\n        Cordobas = 159460001,\n"
            "        /// <summary>Dolares</summary>\n        Dolares = 159460002,\n"
            "    }\n}\n")
        self.assertEqual(self.generar(), esperado)

    def test_los_enums_salen_en_el_orden_de_los_archivos_y_siempre_igual(self):
        self.poner(TIPO_ARREGLO, "b_tipo.md")
        self.poner(MONEDA, "a_moneda.md")
        self.poner(ESTADO_VERSION, "c_estado.md")
        primero = self.generar()
        self.assertEqual(re.findall(r"public enum (\w+)", primero), ["Moneda", "TipoDeArreglo", "EstadoDeVersionDePlantilla"])
        self.assertEqual(self.generar(), primero)

    def test_el_texto_de_la_documentacion_se_escapa_como_xml(self):
        datos = componente(opciones=[{"valor": 159460001, "etiqueta": por_idioma("Cobro & pago <x>"), "descripcion": ""}])
        self.poner(datos)
        texto = self.generar()
        self.assertIn("/// <summary>Cobro &amp; pago &lt;x&gt;</summary>", texto)
        self.assertIn("CobroPagoX = 159460001,", texto)

    def test_dos_choices_se_separan_con_una_linea_en_blanco(self):
        self.poner(MONEDA)
        self.poner(TIPO_ARREGLO)
        self.assertIn("    }\n\n    /// <summary>Choice global <c>sanic_carp_ch_tipoarreglo</c>", self.generar())

    def test_el_displayname_con_caracteres_de_xml_se_escapa_en_la_documentacion(self):
        self.poner(componente(displayname=por_idioma("CH - CARP - Cobro & pago")))
        texto = self.generar()
        self.assertIn("(CH - CARP - Cobro &amp; pago).</summary>", texto)
        self.assertIn("public enum CobroPago", texto)

    def test_solo_se_leen_los_archivos_md_de_la_carpeta(self):
        self.poner(MONEDA)
        with open(os.path.join(self.carpeta, "LEEME.txt"), "w", encoding="utf-8") as f:
            f.write("no es un playbook")
        self.assertEqual(re.findall(r"public enum (\w+)", self.generar()), ["Moneda"])

    def test_la_descripcion_del_choice_no_entra_en_el_codigo(self):
        self.poner(MONEDA)
        self.assertNotIn("nicaragüenses", self.generar())


