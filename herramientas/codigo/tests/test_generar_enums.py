class LaConfiguracionManda(Temporal):
    """El destino, el namespace y la carpeta de playbooks salen de `proyecto.json`; nada de eso está en el código."""

    def test_el_namespace_sale_de_la_configuracion(self):
        self.poner(MONEDA)
        self.assertIn("namespace Prueba.Plugins.Dominio\n", self.generar())
        otra = {"playbooks": CONFIG["playbooks"], "codigo": dict(CONFIG["codigo"], enums_namespace="Otro.Espacio")}
        texto = self.generar(otra)
        self.assertIn("namespace Otro.Espacio\n", texto)
        self.assertNotIn("Prueba.Plugins", texto)

    def test_la_carpeta_de_playbooks_sale_de_la_configuracion(self):
        self.poner(MONEDA)
        otra = {"playbooks": "otra-carpeta", "codigo": CONFIG["codigo"]}
        self.falla(os.path.join(self.raiz, "otra-carpeta", "choice-global"), otra)
        os.makedirs(os.path.join(self.raiz, "otra-carpeta", "choice-global"))
        with open(os.path.join(self.raiz, "otra-carpeta", "choice-global", "m.md"), "w", encoding="utf-8") as f:
            f.write(playbook_md(IDENTIDAD_VALIDA, TIPO_ARREGLO))
        texto = self.generar(otra)
        self.assertIn("public enum TipoDeArreglo", texto)
        self.assertNotIn("public enum Moneda", texto)
        self.assertIn("desde otra-carpeta/choice-global/.", texto)

    def test_el_destino_sale_de_la_configuracion(self):
        self.assertEqual(ge.destino(CONFIG, self.raiz), os.path.join(self.raiz, "salida", "Dominio", "Choices.g.cs"))
        otra = {"playbooks": CONFIG["playbooks"], "codigo": dict(CONFIG["codigo"], enums_destino="x/Otro.cs")}
        self.assertEqual(ge.destino(otra, self.raiz), os.path.join(self.raiz, "x/Otro.cs"))

    def test_sin_configuracion_explicita_se_lee_proyecto_json(self):
        with open(ARCHIVO_CONFIGURACION, encoding="utf-8") as f:
            real = json.load(f)
        self.assertEqual(ge.destino(), os.path.join(RAIZ_PROYECTO, real["codigo"]["enums_destino"]))
        self.assertEqual(ge.namespace(), real["codigo"]["enums_namespace"])
        self.assertEqual(ge.carpeta_de_choices(), os.path.join(RAIZ_PROYECTO, real["playbooks"], "choice-global"))
        # Y la carpeta de playbooks real se lee de la clave `playbooks`, relativa a la raíz que se le pase.
        os.makedirs(os.path.join(self.raiz, real["playbooks"], "choice-global"))
        with open(os.path.join(self.raiz, real["playbooks"], "choice-global", "m.md"), "w", encoding="utf-8") as f:
            f.write(playbook_md(IDENTIDAD_VALIDA, MONEDA))
        self.assertIn(f"namespace {real['codigo']['enums_namespace']}\n", ge.generar(raiz=self.raiz))

    def test_una_configuracion_incompleta_dice_que_clave_falta(self):
        casos = [({}, "playbooks"), ({"playbooks": "p"}, "codigo"), ({"playbooks": "p", "codigo": {}}, "codigo.enums_destino"),
                 ({"playbooks": "p", "codigo": {"enums_destino": "d.cs"}}, "codigo.enums_namespace"),
                 ({"playbooks": 3, "codigo": CONFIG["codigo"]}, "playbooks"),
                 ({"playbooks": "p", "codigo": {"enums_destino": "", "enums_namespace": "A.B"}}, "codigo.enums_destino"),
                 ({"playbooks": "p", "codigo": {"enums_destino": "d.cs", "enums_namespace": None}}, "codigo.enums_namespace")]
        for config, clave in casos:
            with self.subTest(repr(config)):
                self.falla(clave, config)

    def test_un_namespace_que_no_es_de_csharp_es_error(self):
        for malo in ("Mi Espacio", "A..B", ".A", "A.", "1A.B", "A.B-C"):
            with self.subTest(malo):
                otra = {"playbooks": CONFIG["playbooks"], "codigo": dict(CONFIG["codigo"], enums_namespace=malo)}
                self.falla("enums_namespace", otra)


class Principal(Temporal):
    def correr(self, argv, config=CONFIG):
        salida = io.StringIO()
        with contextlib.redirect_stdout(salida):
            codigo = ge.main(argv, config, self.raiz)
        return codigo, salida.getvalue()

    @property
    def destino(self):
        return ge.destino(CONFIG, self.raiz)

    def test_escribe_el_archivo_en_el_destino_de_la_configuracion(self):
        self.poner(MONEDA)
        codigo, texto = self.correr([])
        self.assertEqual(codigo, 0, texto)
        with open(self.destino, encoding="utf-8") as f:
            self.assertEqual(f.read(), self.generar())
        self.assertIn(os.path.join("salida", "Dominio", "Choices.g.cs"), texto)
        self.assertFalse(os.path.exists(os.path.join(self.raiz, "src")))

    def test_comprobar_con_el_archivo_al_dia(self):
        self.poner(MONEDA)
        self.correr([])
        codigo, texto = self.correr(["--comprobar"])
        self.assertEqual(codigo, 0, texto)
        self.assertIn("Choices.g.cs está al día", texto)

    def test_comprobar_con_el_archivo_desactualizado_o_ausente_falla_y_no_escribe(self):
        self.poner(MONEDA)
        codigo, texto = self.correr(["--comprobar"])
        self.assertEqual(codigo, 1, texto)
        self.assertIn("Choices.g.cs está desactualizado", texto)
        self.assertFalse(os.path.exists(self.destino))
        self.correr([])
        self.poner(TIPO_ARREGLO)
        with open(self.destino, encoding="utf-8") as f:
            antes = f.read()
        codigo, texto = self.correr(["--comprobar"])
        self.assertEqual(codigo, 1, texto)
        with open(self.destino, encoding="utf-8") as f:
            self.assertEqual(f.read(), antes)

    def test_el_nombre_del_archivo_en_los_mensajes_sale_del_destino(self):
        self.poner(MONEDA)
        otra = {"playbooks": CONFIG["playbooks"], "codigo": dict(CONFIG["codigo"], enums_destino="x/Enums.g.cs")}
        codigo, texto = self.correr(["--comprobar"], otra)
        self.assertEqual(codigo, 1)
        self.assertIn("Enums.g.cs está desactualizado", texto)
        self.assertNotIn("Choices", texto)


class ElArchivoDelRepo(unittest.TestCase):
    def test_el_archivo_del_repo_esta_al_dia(self):
        destino = ge.destino()
        playbooks = ge.rutas_de_playbooks()
        if not playbooks and not os.path.exists(destino):
            self.skipTest(f"todavia no hay playbooks de choice global en {ge.carpeta_de_choices()}: no hay nada que generar ni que comparar "
                          f"(cuando existan, esta prueba compara {os.path.relpath(destino, RAIZ_PROYECTO)} con lo que genera el playbook)")
        self.assertTrue(playbooks, f"existe {destino} pero no hay playbooks de choice global de los que salga")
        self.assertTrue(os.path.exists(destino), f"hay playbooks de choice global pero falta {destino}: correr herramientas/codigo/generar_enums.py")
        with open(destino, encoding="utf-8") as f:
            self.assertEqual(f.read(), ge.generar(), "correr herramientas/codigo/generar_enums.py")


