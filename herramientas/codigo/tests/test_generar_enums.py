class Temporal(unittest.TestCase):
    """Una raíz de proyecto temporal con su carpeta de playbooks de choice global."""

    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        self.raiz = self.dir.name
        self.carpeta = os.path.join(self.raiz, CONFIG["playbooks"], "choice-global")
        os.makedirs(self.carpeta)

    def poner(self, datos, nombre=None, ident=None):
        ruta = os.path.join(self.carpeta, nombre or datos["nombre"] + ".md")
        with open(ruta, "w", encoding="utf-8") as f:
            f.write(playbook_md(ident or IDENTIDAD_VALIDA, datos))
        return ruta

    def generar(self, config=CONFIG):
        return ge.generar(config, self.raiz)

    def falla(self, fragmento, config=CONFIG):
        with self.assertRaises(SystemExit) as e:
            ge.generar(config, self.raiz)
        self.assertIsInstance(e.exception.code, str)
        self.assertIn(fragmento, e.exception.code)
        return e.exception.code


